#!/usr/bin/env node
/** Write docs/search-config.js from env (public anon key). */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');

function loadEnv() {
  for (const p of [join(root, '.env'), join(root, '..', 'castalia.institute', '.env')]) {
    try {
      for (const line of readFileSync(p, 'utf8').split('\n')) {
        const m = line.match(/^([A-Z0-9_]+)=(.*)$/);
        if (m && !process.env[m[1]]) process.env[m[1]] = m[2].replace(/^["']|["']$/g, '');
      }
    } catch {
      /* next */
    }
  }
}

loadEnv();
const url = process.env.SUPABASE_URL || process.env.NEXT_PUBLIC_SUPABASE_URL;
const anon = process.env.SUPABASE_ANON_KEY || process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY;
if (!url || !anon) {
  console.warn('Skip search-config.js (missing SUPABASE_URL / ANON_KEY)');
  process.exit(0);
}

const out = `// Generated by scripts/build-search-config.js — public anon key
window.CASTALIA_QUOTES_SUPABASE_URL = ${JSON.stringify(url)};
window.CASTALIA_QUOTES_SUPABASE_ANON_KEY = ${JSON.stringify(anon)};
`;
writeFileSync(join(root, 'docs', 'search-config.js'), out);
console.log('Wrote docs/search-config.js');
